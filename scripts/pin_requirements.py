"""Regenerates the pinned dependency files from the packages installed in the current venv.

  requirements.in    what DADS needs directly (version ranges) - edit this one by hand
  requirements.txt   the same packages pinned to the exact versions tested (pip install -r requirements.txt)
  constraints.txt    exact versions of everything those packages pull in (pip install -r requirements.txt -c constraints.txt)

Only the dependency tree of requirements.in is pinned, not whatever else happens to be installed in the venv.
Upgrade flow: pip install -U <pkg> in the venv, run the tests, then: python scripts/pin_requirements.py
"""
import os
import re
import sys
from importlib import metadata

from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = os.path.join(os.path.dirname(__file__), "..")
HEADER = "# GENERATED by scripts/pin_requirements.py from requirements.in - do not edit by hand.\n"


def _canon(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _requirements(path: str):
    with open(path) as f:
        return [Requirement(line.split("#")[0].strip()) for line in f if line.split("#")[0].strip()]


def _deps(dist_name: str, extras=()):
    """Requirements of an installed distribution. Platform / Python-version markers are not evaluated (a
    dependency needed only on another OS is followed if it is installed here, else skipped); extras are
    followed only when requested."""
    out = []
    env = default_environment()
    for raw in metadata.requires(dist_name) or []:
        req = Requirement(raw)
        if req.marker is None or "extra" not in str(req.marker) \
                or any(req.marker.evaluate(dict(env, extra=e)) for e in extras):
            out.append(req)
    return out


def main() -> int:
    direct = _requirements(os.path.join(ROOT, "requirements.in"))
    pinned, seen, queue = {}, set(), [(r.name, tuple(r.extras)) for r in direct]
    while queue:
        name, extras = queue.pop()
        key = (_canon(name), extras)
        if key in seen:
            continue
        seen.add(key)
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            print(f"  not installed here (left unpinned): {name}")
            continue
        pinned[_canon(name)] = (dist.metadata["Name"], dist.version)
        queue.extend((d.name, tuple(d.extras)) for d in _deps(dist.metadata["Name"], extras))

    direct_names = {_canon(r.name) for r in direct}
    with open(os.path.join(ROOT, "requirements.txt"), "w") as f:
        f.write(HEADER + "# Exact versions of DADS's direct dependencies; their own dependencies are pinned in constraints.txt.\n"
                "# CPU-only torch: pip install torch==<version below> --index-url https://download.pytorch.org/whl/cpu\n")
        for r in direct:
            name, version = pinned.get(_canon(r.name), (r.name, None))
            extras = f"[{','.join(sorted(r.extras))}]" if r.extras else ""
            f.write(f"{name}{extras}=={version}\n" if version else f"{r}\n")
    with open(os.path.join(ROOT, "constraints.txt"), "w") as f:
        f.write(HEADER + "# Exact versions of the packages DADS's dependencies pull in. Use with: -c constraints.txt\n")
        for key in sorted(pinned):
            if key not in direct_names:
                name, version = pinned[key]
                f.write(f"{name}=={version}\n")
    print(f"requirements.txt: {len(direct)} pinned; constraints.txt: {len(pinned) - len(direct_names & pinned.keys())} pinned "
          f"(Python {sys.version.split()[0]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
